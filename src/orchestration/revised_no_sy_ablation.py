def _find_record(manifest: dict[str, Any], condition: str, replicate: int) -> dict[str, Any] | None:
    for record in manifest.get("runs") or []:
        if (
            isinstance(record, dict)
            and record.get("condition") == condition
            and record.get("replicate") == replicate
        ):
            return record
    return None


def _finalize(manifest: dict[str, Any], suite_root: Path) -> dict[str, Any]:
    summary = build_summary(manifest)
    manifest["status"] = summary["status"]
    manifest["completed_at"] = _utc_now()
    _write_json(suite_root / "ablation_suite_manifest.json", manifest)
    summary = build_summary(manifest)
    _write_json(suite_root / "ablation_summary.json", summary)
    _write_text(suite_root / "ablation_summary.md", render_summary_markdown(summary))
    return summary


def _local_env() -> dict[str, str]:
    environment = os.environ.copy()
    source = str(PROJECT_ROOT / "src")
    current = environment.get("PYTHONPATH", "")
    environment["PYTHONPATH"] = source if not current else source + os.pathsep + current
    return environment


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.expanduser().resolve().open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _load_json(path: Path) -> dict[str, Any]:
    resolved = path.expanduser().resolve()
    payload = json.loads(resolved.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"JSON object required: {resolved}")
    return payload


def _write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _write_text(path: Path, value: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding="utf-8")


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


