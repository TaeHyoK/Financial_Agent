"""Recompose a no-SY-centred paper ablation suite from existing artifacts.

The revised baseline is an already-generated ``no_sy`` report.  Only the
Strategy and Writer stages are regenerated for the two combined ablations:

* ``no_peer``: no SY and no competitor evidence.
* ``no_subdata``: no SY and primary-data-only domain outputs.

Collection and domain-agent outputs are never regenerated by this runner.
"""

from __future__ import annotations

